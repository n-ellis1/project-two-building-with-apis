"""Django settings for the video game tracker.

Secrets and the debug flag come from the git-ignored `.env` file (see `.env.example`).
IGDB credentials are optional: Django starts without them, and only IGDB features
report a configuration error.
"""

import os
from pathlib import Path

from django.contrib.messages import constants as message_constants
from django.core.exceptions import ImproperlyConfigured
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent.parent

# Values already set in the process environment win over the file.
# DJANGO_ENV_FILE points at a different file (tests use it to avoid the real .env).
load_dotenv(os.environ.get("DJANGO_ENV_FILE") or BASE_DIR / ".env")


def env_bool(name: str, default: bool = False) -> bool:
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


SECRET_KEY = os.environ.get("DJANGO_SECRET_KEY", "")
if not SECRET_KEY:
    raise ImproperlyConfigured("DJANGO_SECRET_KEY is not set. Add it to .env (see .env.example).")

DEBUG = env_bool("DJANGO_DEBUG", default=False)

